#!/usr/bin/env node
import { readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

const root = resolve('.');
const version = readFileSync(join(root, 'VERSION'), 'utf-8').trim();
const target = join(root, 'src', 'version.ts');
const next = `// Auto-generated by scripts/sync-runtime-version.mjs
export const APP_VERSION = '${version}';
`;
const prev = (() => {
  try {
    return readFileSync(target, 'utf-8');
  } catch {
    return '';
  }
})();
if (prev !== next) {
  writeFileSync(target, next);
  console.log(`Synced runtime version module => ${version}`);
} else {
  console.log(`Runtime version module already synced => ${version}`);
}
